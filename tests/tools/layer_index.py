"""
Generate an index of the suite grouped by test layer.

The tests are organised on disk by feature, because many of them belong
to two layers at once - a test proving a deactivated listing vanishes
from search is both integration and regression. Filing each test in one
folder would force an arbitrary choice and make the folder a misleading
picture of the layer.

Instead every test carries one or more layer markers, and this script
reads them back out to produce the layer view: which tests belong to UI,
to security, to integration, and so on. The result goes into the Phase 5
report.

Run it from the tests folder:

    python tools/layer_index.py

It writes reports/layer-index.md and prints a summary.
"""

from __future__ import annotations

import subprocess
import sys
from collections import defaultdict
from pathlib import Path

LAYERS = [
    ("ui", "UI", "Interface rendering, layout and accessibility"),
    ("functional", "Functional", "Business rules and validation"),
    ("integration", "Integration", "Data reaching and leaving MySQL"),
    ("e2e", "End-to-end", "Complete journeys across several pages"),
    ("regression", "Regression", "Guards against previously fixed defects"),
    ("security", "Security", "Input handling, CSRF, escaping, disclosure"),
    ("logic", "Logic", "Pure calculation, no browser needed"),
]

ROOT = Path(__file__).resolve().parent.parent


def collect(marker: str) -> list[str]:
    """Every test id carrying this marker, without running anything."""
    result = subprocess.run(
        [
            sys.executable,
            "-m",
            "pytest",
            "--collect-only",
            "-q",
            "--no-header",
            "-p",
            "no:cacheprovider",
            "-m",
            marker,
        ],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )

    ids = []
    for line in result.stdout.splitlines():
        line = line.strip()
        if "::" in line and line.startswith("suites"):
            # Drop the browser parameter pytest-playwright appends.
            ids.append(line.split("[")[0])
    return sorted(set(ids))


def main() -> int:
    print("\n  Collecting tests by layer. This runs nothing - it only reads.\n")

    by_layer: dict[str, list[str]] = {}
    for marker, _, _ in LAYERS:
        by_layer[marker] = collect(marker)
        print(f"    {marker:<12} {len(by_layer[marker]):>3} tests")

    # A test may carry several markers, so the layer totals add up to
    # more than the suite size. Count the distinct tests too.
    distinct: set[str] = set()
    for ids in by_layer.values():
        distinct.update(ids)

    per_file: dict[str, int] = defaultdict(int)
    for test_id in distinct:
        per_file[test_id.split("::")[0]] += 1

    out = ROOT / "reports"
    out.mkdir(exist_ok=True)
    path = out / "layer-index.md"

    lines: list[str] = [
        "# Test suite — index by layer",
        "",
        "Generated by `python tools/layer_index.py`.",
        "",
        "Tests are organised on disk by feature. Layer membership is",
        "recorded with markers, because a test often belongs to more than",
        "one layer — which is why the layer totals below add up to more",
        "than the number of tests in the suite.",
        "",
        "Run any single layer with, for example, `pytest -m security`.",
        "",
        "## Summary",
        "",
        "| Layer | Tests | What it covers |",
        "| --- | ---: | --- |",
    ]

    for marker, title, blurb in LAYERS:
        lines.append(f"| {title} | {len(by_layer[marker])} | {blurb} |")

    lines += [
        "",
        f"**{len(distinct)} distinct tests** across "
        f"{len(per_file)} files.",
        "",
        "## By file",
        "",
        "| File | Tests |",
        "| --- | ---: |",
    ]
    for file_name in sorted(per_file):
        lines.append(f"| `{file_name}` | {per_file[file_name]} |")

    for marker, title, blurb in LAYERS:
        lines += ["", f"## {title}", "", f"_{blurb}_", ""]
        if not by_layer[marker]:
            lines.append("_No tests carry this marker._")
            continue
        for test_id in by_layer[marker]:
            file_part, test_part = test_id.split("::", 1)
            readable = test_part.replace("test_", "").replace("_", " ")
            lines.append(f"- **{readable}** — `{file_part}`")

    path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"\n  {len(distinct)} distinct tests across {len(per_file)} files.")
    print(f"  Written to {path}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
